public class Persona
{

private string nombre;
private string apellido;
private string documento;
private string correo;
private string telefono;

public Persona( string nombreRecibido, string apellidoRecibido, string
documentoRecibido, string correoRecibido, string telefonoRecibido)
{
this.nombre = nombreRecibido;
this.apellido = apellidoRecibido;
this.documento = documentoRecibido;
this.correo = correoRecibido;
this.telefono = telefonoRecibido;


}

}




